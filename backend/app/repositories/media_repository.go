func (r *postgresMediaRepository) UpdateMetadata(ctx context.Context, id interface{}, metadata map[string]interface{}) error {
	// Convert interface{} to int
	var mediaID int

	switch v := id.(type) {
	case int:
		mediaID = v
	case string:
		return fmt.Errorf("string IDs not supported, expected integer")
	case int64:
		mediaID = int(v)
	case float64:
		mediaID = int(v)
	default:
		return fmt.Errorf("unsupported ID type: %T", id)
	}

	// Build update query dynamically based on metadata fields
	updateFields := []string{}
	args := []interface{}{}
	argIndex := 1

	if filename, ok := metadata["filename"]; ok {
		updateFields = append(updateFields, fmt.Sprintf("filename = $%d", argIndex))
		args = append(args, filename)
		argIndex++
	}

	if originalFilename, ok := metadata["original_filename"]; ok {
		updateFields = append(updateFields, fmt.Sprintf("original_filename = $%d", argIndex))
		args = append(args, originalFilename)
		argIndex++
	}

	if thumbnailPath, ok := metadata["thumbnail_path"]; ok {
		updateFields = append(updateFields, fmt.Sprintf("thumbnail_path = $%d", argIndex))
		args = append(args, thumbnailPath)
		argIndex++
	}

	if metadataJSON, ok := metadata["metadata"]; ok {
		updateFields = append(updateFields, fmt.Sprintf("metadata = $%d", argIndex))
		args = append(args, metadataJSON)
		argIndex++
	}

	if isActive, ok := metadata["is_active"]; ok {
		updateFields = append(updateFields, fmt.Sprintf("is_active = $%d", argIndex))
		args = append(args, isActive)
		argIndex++
	}

	if len(updateFields) == 0 {
		return errors.New("no valid metadata fields to update")
	}

	// Add ID for WHERE clause
	args = append(args, mediaID)

	query := fmt.Sprintf("UPDATE media_items SET %s WHERE id = $%d",
		strings.Join(updateFields, ", "), argIndex)

	result, err := r.db.ExecContext(ctx, query, args...)
	if err != nil {
		log.Printf("Error updating media metadata for %d: %v", mediaID, err)
		return fmt.Errorf("failed to update media metadata: %w", err)
	}

	rowsAffected, _ := result.RowsAffected()
	if rowsAffected == 0 {
		return errors.New("media record not found")
	}

	log.Printf("Media metadata updated successfully for %d", mediaID)
	return nil
}

