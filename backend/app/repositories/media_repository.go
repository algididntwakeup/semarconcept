// postgresMediaRepository implements the MediaRepository interface.
type postgresMediaRepository struct {
	db *sqlx.DB
}

// NewPostgresMediaRepository creates a new instance of postgresMediaRepository.
func NewPostgresMediaRepository(db *sqlx.DB) MediaRepository {
	if db == nil {
		log.Fatal("repositories: NewPostgresMediaRepository requires a non-nil *sqlx.DB")
	}
	return &postgresMediaRepository{db: db}
}

func (r *postgresMediaRepository) Create(ctx context.Context, media *models.Media) error {
	// ID will be auto-generated by database (autoIncrement)
	media.UploadedAt = time.Now()

	// Sync legacy fields to database fields
	if err := media.BeforeSave(); err != nil {
		return fmt.Errorf("failed to prepare media for save: %w", err)
	}

	query := `
        INSERT INTO media_items (
            filename, original_filename, mime_type, file_size, file_path, 
            thumbnail_path, metadata, is_active, uploaded_at, uploaded_by, tenant_id
        ) VALUES (
            :filename, :original_filename, :mime_type, :file_size, :file_path,
            :thumbnail_path, :metadata, :is_active, :uploaded_at, :uploaded_by, :tenant_id
        ) RETURNING id
    `

	rows, err := r.db.NamedQueryContext(ctx, query, media)
	if err != nil {
		log.Printf("Error creating media record for '%s': %v", media.Filename, err)
		return fmt.Errorf("failed to create media record: %w", err)
	}
	defer rows.Close()

	if rows.Next() {
		if err := rows.Scan(&media.ID); err != nil {
			return fmt.Errorf("failed to scan returned ID: %w", err)
		}
	}

	log.Printf("Media record created successfully for '%s' with ID: %d", media.Filename, media.ID)
	return nil
}

func (r *postgresMediaRepository) GetByID(ctx context.Context, id interface{}) (*models.Media, error) {
	// Convert interface{} to int
	var mediaID int
	var err error

	switch v := id.(type) {
	case int:
		mediaID = v
	case string:
		return nil, fmt.Errorf("string IDs not supported, expected integer")
	case int64:
		mediaID = int(v)
	case float64:
		mediaID = int(v)
	default:
		return nil, fmt.Errorf("unsupported ID type: %T", id)
	}

	var media models.Media
	query := `SELECT * FROM media_items WHERE id = $1`
	err = r.db.GetContext(ctx, &media, query, mediaID)
	if err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return nil, errors.New("media record not found")
		}
		log.Printf("Error getting media record by ID %d: %v", mediaID, err)
		return nil, fmt.Errorf("failed to get media record by ID: %w", err)
	}

	// Populate legacy fields for backward compatibility
	if err := media.AfterFind(); err != nil {
		log.Printf("Warning: failed to populate legacy fields: %v", err)
	}

	return &media, nil
}

